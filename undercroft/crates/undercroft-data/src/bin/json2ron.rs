//! json2ron — deserialise `tools/export/out/*.json` (written by `tools/export/export.mjs` from the prototype's
//! ES modules) into the typed structs of `undercroft_data` and write pretty RON into `assets/data/`, so the
//! committed RON is guaranteed to match the Rust types.
//!
//! ```sh
//! cd undercroft/tools/export && node export.mjs
//! cd undercroft && cargo run -p undercroft-data --bin json2ron    # [in_dir] [out_dir] override the defaults
//! ```

use serde::{de::DeserializeOwned, Serialize};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use undercroft_data::models::ModelTable;
use undercroft_data::tables::{BuildingTable, ContractTable, EndgameData, NpcTable};
use undercroft_data::zone::{Palette, ZoneDef};
use undercroft_data::{Config, GameData};

fn convert<T: DeserializeOwned + Serialize>(
    input: &Path,
    output: &Path,
    name: &str,
) -> Result<(), String> {
    let json_path = input.join(format!("{name}.json"));
    let text =
        std::fs::read_to_string(&json_path).map_err(|e| format!("{}: {e}", json_path.display()))?;
    let value: T =
        serde_json::from_str(&text).map_err(|e| format!("{}: {e}", json_path.display()))?;
    let pretty = ron::ser::PrettyConfig::new()
        .depth_limit(usize::MAX)
        .new_line("\n")
        .indentor("  ");
    let ron_text = ron::ser::to_string_pretty(&value, pretty)
        .map_err(|e| format!("{name}: serialise: {e}"))?;
    // round trip: what we wrote must read back identically
    let back: T =
        ron::from_str(&ron_text).map_err(|e| format!("{name}: RON round trip failed: {e}"))?;
    let again =
        ron::ser::to_string_pretty(&back, ron::ser::PrettyConfig::new().depth_limit(usize::MAX))
            .map_err(|e| format!("{name}: re-serialise: {e}"))?;
    let first = ron::ser::to_string_pretty(
        &value,
        ron::ser::PrettyConfig::new().depth_limit(usize::MAX),
    )
    .map_err(|e| format!("{name}: re-serialise: {e}"))?;
    if again != first {
        return Err(format!("{name}: RON round trip changed the data"));
    }
    let out_path = output.join(format!("{name}.ron"));
    let header = format!(
        "// {name}.ron — generated by tools/export/export.mjs + json2ron from prototype/src. Do not edit by hand.\n"
    );
    std::fs::write(&out_path, header + &ron_text + "\n")
        .map_err(|e| format!("{}: {e}", out_path.display()))?;
    println!("wrote {}", out_path.display());
    Ok(())
}

fn run() -> Result<(), String> {
    let args: Vec<String> = std::env::args().collect();
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let input: PathBuf = args
        .get(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("tools/export/out"));
    let output: PathBuf = args
        .get(2)
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("assets/data"));
    std::fs::create_dir_all(&output).map_err(|e| format!("{}: {e}", output.display()))?;
    convert::<Config>(&input, &output, "config")?;
    convert::<BTreeMap<String, Palette>>(&input, &output, "palettes")?;
    convert::<Vec<ZoneDef>>(&input, &output, "zones")?;
    convert::<ContractTable>(&input, &output, "contracts")?;
    convert::<NpcTable>(&input, &output, "npcs")?;
    convert::<BuildingTable>(&input, &output, "buildings")?;
    convert::<EndgameData>(&input, &output, "endgame")?;
    convert::<ModelTable>(&input, &output, "models")?;
    // final check: the whole directory loads (RON + the map .txt files the exporter wrote)
    let data = GameData::from_dir(&output).map_err(|e| format!("reload: {e}"))?;
    println!(
        "reloaded {}: {} zones, {} contracts, {} models",
        output.display(),
        data.zones.len(),
        data.contracts.contracts.len(),
        data.models.models.len()
    );
    Ok(())
}

fn main() {
    if let Err(e) = run() {
        eprintln!("json2ron: {e}");
        std::process::exit(1);
    }
}
